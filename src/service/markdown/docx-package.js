const JSZip = require('jszip')
const { DOMParser, XMLSerializer } = require('@xmldom/xmldom')
const path = require('path').posix

const W = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main'
const R = 'http://schemas.openxmlformats.org/officeDocument/2006/relationships'
const REL = 'http://schemas.openxmlformats.org/package/2006/relationships'
const CT = 'http://schemas.openxmlformats.org/package/2006/content-types'
const WORD = 'http://schemas.microsoft.com/office/word'
const A = 'http://schemas.openxmlformats.org/drawingml/2006/main'
const SVG = 'http://schemas.microsoft.com/office/drawing/2016/SVG/main'
const SVG_EXTENSION = '{96DAC541-7B7A-43D3-8B79-37D633B846F1}'
const orders = {
    pPr: 'pStyle keepNext keepLines pageBreakBefore framePr widowControl numPr suppressLineNumbers pBdr shd tabs suppressAutoHyphens kinsoku wordWrap overflowPunct topLinePunct autoSpaceDE autoSpaceDN bidi adjustRightInd snapToGrid spacing ind contextualSpacing mirrorIndents suppressOverlap jc textDirection textAlignment textboxTightWrap outlineLvl divId cnfStyle rPr sectPr pPrChange',
    tcPr: 'cnfStyle tcW gridSpan hMerge vMerge tcBorders shd noWrap tcMar textDirection tcFitText vAlign hideMark headers cellIns cellDel cellMerge tcPrChange',
    tblPr: 'tblStyle tblpPr tblOverlap bidiVisual tblStyleRowBandSize tblStyleColBandSize tblW jc tblCellSpacing tblInd tblBorders shd tblLayout tblCellMar tblLook tblCaption tblDescription tblPrChange',
    tblBorders: 'top left start bottom right end insideH insideV',
    tcBorders: 'top left start bottom right end insideH insideV tl2br tr2bl',
    tblCellMar: 'top left start bottom right end',
}

function children(node, ns, name) {
    return Array.from(node.childNodes).filter(n => n.nodeType === 1 &&
        (!ns || n.namespaceURI === ns) && (!name || n.localName === name))
}

function parseXml(xml, part) {
    // DOCX generated by this exporter never needs DTDs or external entities.
    if (/<!DOCTYPE/i.test(xml)) throw new Error(`DOCX: DTD is not supported in ${part}`)
    return new DOMParser({ onError(level, message) {
        throw new Error(`DOCX: invalid XML in ${part}: ${message}`)
    } }).parseFromString(xml, 'application/xml')
}

function sortProperties(root) {
    for (const [name, order] of Object.entries(orders)) {
        const rank = new Map(order.split(' ').map((value, index) => [value, index]))
        for (const node of Array.from(root.getElementsByTagNameNS(W, name))) {
            const elements = children(node)
            // Fail rather than silently moving unknown extension markup.
            if (elements.some(e => e.namespaceURI !== W || !rank.has(e.localName))) {
                throw new Error(`DOCX: unsupported child in ${name}`)
            }
            if (new Set(elements.map(e => e.localName)).size !== elements.length) {
                throw new Error(`DOCX: duplicate property in ${name}`)
            }
            const sorted = [...elements].sort((a, b) => rank.get(a.localName) - rank.get(b.localName))
            if (sorted.some((e, i) => e !== elements[i])) {
                for (const e of sorted) node.appendChild(e)
            }
        }
    }
}

function normalizeTables(doc) {
    for (const table of Array.from(doc.getElementsByTagNameNS(W, 'tbl'))) {
        const grids = children(table, W, 'tblGrid')
        if (!grids.length) throw new Error('DOCX: table has no grid')
        const signature = grid => children(grid).map(col => {
            if (col.namespaceURI !== W || col.localName !== 'gridCol') {
                throw new Error('DOCX: unsupported table grid content')
            }
            return col.getAttributeNS(W, 'w')
        })
        const first = JSON.stringify(signature(grids[0]))
        if (grids.some(g => JSON.stringify(signature(g)) !== first)) {
            throw new Error('DOCX: conflicting table grids; refusing to discard column widths')
        }
        // html-to-docx emits a second identical grid between thead and tbody.
        for (const duplicate of grids.slice(1)) table.removeChild(duplicate)
        const properties = children(table, W, 'tblPr')[0]
        const next = properties ? properties.nextSibling : table.firstChild
        if (next !== grids[0]) table.insertBefore(grids[0], next)
        let previous = new Map()
        for (const row of children(table, W, 'tr')) {
            const current = new Map()
            const rowProperties = children(row, W, 'trPr')[0]
            let column = Number(rowProperties && children(rowProperties, W, 'gridBefore')[0]?.getAttributeNS(W, 'val')) || 0
            for (const cell of children(row, W, 'tc')) {
                const properties = children(cell, W, 'tcPr')[0]
                const span = properties && children(properties, W, 'gridSpan')[0]
                const merge = properties && children(properties, W, 'vMerge')[0]
                const continuing = merge && merge.getAttributeNS(W, 'val') !== 'restart'
                let width = span ? Number(span.getAttributeNS(W, 'val')) : 1
                if (width === 0 && continuing && previous.get(column)?.merged) {
                    // The generator writes gridSpan=0 for a continued rowspan.
                    width = previous.get(column).width
                    span.setAttributeNS(W, 'w:val', String(width))
                }
                if (!Number.isInteger(width) || width < 1) throw new Error('DOCX: invalid cell grid span')
                current.set(column, { width, merged: Boolean(merge) })
                column += width
            }
            previous = current
        }
    }
    // CT_Body permits its document-level section properties only after blocks.
    for (const body of Array.from(doc.getElementsByTagNameNS(W, 'body'))) {
        const sections = children(body, W, 'sectPr')
        if (sections.length > 1) throw new Error('DOCX: multiple body section properties')
        if (sections.length && elementsAfter(sections[0])) body.appendChild(sections[0])
    }
    sortProperties(doc)
}

function elementsAfter(node) {
    for (let next = node.nextSibling; next; next = next.nextSibling) {
        if (next.nodeType === 1) return true
    }
    return false
}

function setCompatibilityMode(doc) {
    const settings = doc.documentElement
    if (settings.namespaceURI !== W || settings.localName !== 'settings') {
        throw new Error('DOCX: invalid settings root')
    }
    let compat = children(settings, W, 'compat')[0]
    if (!compat) {
        compat = doc.createElementNS(W, 'w:compat')
        // These settings follow compat in CT_Settings, unlike defaultTabStop/zoom.
        const following = new Set(('docVars rsids attachedSchema themeFontLang clrSchemeMapping doNotIncludeSubdocsInStats ' +
            'doNotAutoCompressPictures forceUpgrade captions readModeInkLockDown smartTagType schemaLibrary ' +
            'doNotEmbedSmartTags decimalSymbol listSeparator').split(' '))
        const next = children(settings).find(e => following.has(e.localName) ||
            (e.namespaceURI !== W && e.localName === 'mathPr'))
        settings.insertBefore(compat, next || null)
    }
    const modes = children(compat, W, 'compatSetting').filter(e =>
        e.getAttributeNS(W, 'name') === 'compatibilityMode' && e.getAttributeNS(W, 'uri') === WORD)
    const mode = modes[0] || doc.createElementNS(W, 'w:compatSetting')
    mode.setAttributeNS(W, 'w:name', 'compatibilityMode')
    mode.setAttributeNS(W, 'w:uri', WORD)
    mode.setAttributeNS(W, 'w:val', '15')
    if (!mode.parentNode) compat.appendChild(mode)
    for (const duplicate of modes.slice(1)) compat.removeChild(duplicate)
}

function contentTypes(doc) {
    const defaults = new Map()
    const overrides = new Map()
    for (const e of children(doc.documentElement, CT)) {
        const map = e.localName === 'Default' ? defaults : overrides
        const key = e.getAttribute(e.localName === 'Default' ? 'Extension' : 'PartName')
        if (map.has(key)) throw new Error(`DOCX: duplicate Content Type for ${key}`)
        map.set(key, e.getAttribute('ContentType'))
    }
    return part => overrides.get('/' + part) || defaults.get(part.split('.').pop())
}

// SVG is an Office drawing extension, not a raster blip. Keep the original
// vector bytes; do not manufacture a PNG fallback or change external links.
function normalizeSvgDrawings(doc, imageParts, typeOf) {
    for (const blip of Array.from(doc.getElementsByTagNameNS(A, 'blip'))) {
        const id = blip.getAttributeNS(R, 'embed')
        const part = imageParts.get(id)
        if (!part || typeOf(part) !== 'image/svg+xml') continue
        let list = children(blip, A, 'extLst')[0]
        const extensions = list ? children(list, A, 'ext').filter(e => e.getAttribute('uri') === SVG_EXTENSION) : []
        if (extensions.length) {
            const vectors = children(extensions[0], SVG, 'svgBlip')
            if (extensions.length !== 1 || vectors.length !== 1 ||
                vectors[0].getAttributeNS(R, 'embed') !== id || vectors[0].hasAttributeNS(R, 'link')) {
                throw new Error('DOCX: conflicting SVG drawing references')
            }
        } else {
            if (!list) {
                list = doc.createElementNS(A, 'a:extLst')
                blip.appendChild(list)
            }
            const extension = doc.createElementNS(A, 'a:ext')
            extension.setAttribute('uri', SVG_EXTENSION)
            const vector = doc.createElementNS(SVG, 'asvg:svgBlip')
            vector.setAttributeNS(R, 'r:embed', id)
            extension.appendChild(vector)
            list.appendChild(extension)
        }
        // No raster fallback was supplied. Office uses the SVG extension;
        // consumers without SVG support cannot display this vector-only image.
        blip.removeAttributeNS(R, 'embed')
    }
}

/** Normalize the generated package once, before saving (shared by image modes).
 * This is a targeted generator workaround, not a general document repair tool.
 */
async function normalizeDocxPackage(buffer) {
    const zip = await JSZip.loadAsync(buffer, { checkCRC32: true })
    const docs = new Map()
    const originals = new Map()
    const serializer = new XMLSerializer()
    for (const [name, entry] of Object.entries(zip.files)) {
        if (!entry.dir && /\.(xml|rels)$/.test(name)) {
            const doc = parseXml(await entry.async('string'), name)
            docs.set(name, doc)
            originals.set(name, serializer.serializeToString(doc))
        }
    }
    const types = docs.get('[Content_Types].xml')
    const document = docs.get('word/document.xml')
    const settings = docs.get('word/settings.xml')
    if (!types || !document || !settings) throw new Error('DOCX: required package part missing')
    if (types.documentElement.namespaceURI !== CT) throw new Error('DOCX: invalid Content Types root')
    for (const [name, doc] of docs) {
        if (name.startsWith('word/') && !name.endsWith('.rels')) normalizeTables(doc)
    }
    setCompatibilityMode(settings)
    let typeOf = contentTypes(types)
    for (const [name, entry] of Object.entries(zip.files)) {
        if (entry.dir || !/\.(svg|svg\+xml)$/i.test(name)) continue
        const svg = parseXml(await entry.async('string'), name)
        if (svg.documentElement.namespaceURI !== 'http://www.w3.org/2000/svg' || svg.documentElement.localName !== 'svg') {
            throw new Error(`DOCX: invalid SVG image ${name}`)
        }
        if (typeOf(name) !== 'image/svg+xml') {
            const existing = children(types.documentElement, CT, 'Override').find(e => e.getAttribute('PartName') === '/' + name)
            const override = existing || types.createElementNS(CT, 'Override')
            override.setAttribute('PartName', '/' + name)
            override.setAttribute('ContentType', 'image/svg+xml')
            if (!existing) types.documentElement.appendChild(override)
        }
    }
    typeOf = contentTypes(types)
    for (const [name, entry] of Object.entries(zip.files)) {
        if (!entry.dir && name !== '[Content_Types].xml' && !typeOf(name)) {
            throw new Error(`DOCX: missing Content Type for ${name}`)
        }
    }
    const relationships = new Map()
    const imagePartsBySource = new Map()
    for (const [name, doc] of docs) {
        if (!name.endsWith('.rels')) continue
        const source = name === '_rels/.rels' ? '' : path.join(path.dirname(path.dirname(name)), path.basename(name, '.rels'))
        const ids = new Set()
        const imageParts = new Map()
        for (const rel of children(doc.documentElement, REL, 'Relationship')) {
            const id = rel.getAttribute('Id')
            if (!id || ids.has(id)) throw new Error(`DOCX: duplicate or missing Relationship Id in ${name}`)
            ids.add(id)
            if (rel.getAttribute('TargetMode') === 'External') continue
            const target = path.resolve('/', path.dirname(source), decodeURIComponent(rel.getAttribute('Target'))).slice(1)
            if (!zip.file(target)) throw new Error(`DOCX: missing Relationship target ${target}`)
            if (rel.getAttribute('Type') === R + '/image') imageParts.set(id, target)
        }
        relationships.set(source, ids)
        imagePartsBySource.set(source, imageParts)
    }
    for (const [name, doc] of docs) {
        if (name.startsWith('word/') && !name.endsWith('.rels')) {
            normalizeSvgDrawings(doc, imagePartsBySource.get(name) || new Map(), typeOf)
        }
    }
    for (const [name, doc] of docs) {
        for (const element of Array.from(doc.getElementsByTagName('*'))) {
            for (const attr of Array.from(element.attributes)) {
                if (attr.namespaceURI === R && !relationships.get(name)?.has(attr.value)) {
                    throw new Error(`DOCX: unresolved Relationship ${attr.value} in ${name}`)
                }
            }
        }
    }
    for (const [name, doc] of docs) {
        const xml = serializer.serializeToString(doc)
        if (xml !== originals.get(name)) zip.file(name, xml)
    }
    return zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' })
}

module.exports = { normalizeDocxPackage }
